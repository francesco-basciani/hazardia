import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const code=readFileSync('src/hazardia/web/static/domain-home-model.js','utf8');
const {domains,domainById,portalRoute,portalURL}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert.equal(domains.length,9);assert.equal(new Set(domains.map(d=>d.id)).size,9);
assert.equal(domains.filter(d=>!d.planned).length,7);assert.equal(domains.filter(d=>d.planned).length,2);
assert.equal(domainById('weather'),null);assert.equal(domainById('health'),null);assert.equal(domainById('../fire'),null);
assert.deepEqual(portalRoute(''),{view:'home',domain:'all'});
assert.equal(portalRoute('?view=map').view,'map');assert.equal(portalRoute('?view=bogus').view,'home');
assert.deepEqual(portalRoute('?view=results&lab=traffic'),{view:'results',domain:'mobility'});
assert.deepEqual(portalRoute('?view=results&lab=evacuation'),{view:'results',domain:'water'});
assert.deepEqual(portalRoute('?view=results&lab=flood'),{view:'results',domain:'water'});
assert.equal(domainById('water').lab,'flood');
assert.equal(portalRoute('?case=example-one').view,'results');assert.equal(portalRoute('?a=job-one&b=job-two').view,'results');
const u=new URL(portalURL('?a=job-one&b=job-two&case=example-one&section=compare&diagnostics=audit','map','snow'),'http://localhost');
for(const [k,v] of [['a','job-one'],['b','job-two'],['case','example-one'],['section','compare'],['diagnostics','audit'],['view','map'],['domain','snow']])assert.equal(u.searchParams.get(k),v);
assert.equal(new URL(portalURL('?domain=fire','home','all'),'http://localhost').searchParams.has('domain'),false);
assert.equal(domainById('seismic').lab,undefined);assert.equal(domainById('snow').lab,undefined);assert.equal(domainById('mobility').lab,'traffic');
console.log('PASS: 9 domains / 7 linked / 2 planned, shared weather, known labs only, safe routes and preserved case/job/section links');
