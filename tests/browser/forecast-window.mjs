import assert from 'node:assert/strict';import fs from 'node:fs';
const {forecastWindow,usesForecast}=await import('data:text/javascript;base64,'+Buffer.from(fs.readFileSync(new URL('../../src/hazardia/web/static/forecast-window.js',import.meta.url))).toString('base64'));
const rows=Array.from({length:6},(_,i)=>({at:new Date(Date.UTC(2026,9,28,i)).toISOString(),until:new Date(Date.UTC(2026,9,28,i+1)).toISOString(),status:'AVAILABLE',mean_mm:i*5}));
assert.equal(forecastWindow(rows,rows[0].at,3).mean_mm,15);
assert.equal(forecastWindow(rows,rows[1].at,3).mean_mm,30);
assert.notEqual(forecastWindow(rows,rows[0].at,3).band,forecastWindow(rows,rows[1].at,3).band);
assert.equal(forecastWindow(rows,'2026-10-28T00:30:00Z',3).mean_mm,15);
assert.equal(forecastWindow(rows,rows[5].at,3).status,'UNAVAILABLE');
assert.equal(forecastWindow(rows.filter((_,i)=>i!==1),rows[0].at,3).status,'UNAVAILABLE');
assert.equal(forecastWindow(rows.map((r,i)=>i===1?{...r,status:'UNAVAILABLE'}:r),rows[0].at,3).status,'UNAVAILABLE');
assert.equal(forecastWindow([{...rows[0],mean_mm:null}],rows[0].at,1).status,'UNAVAILABLE');
assert.equal(forecastWindow([{...rows[0],mean_mm:-1}],rows[0].at,1).status,'UNAVAILABLE');
assert.equal(forecastWindow([],rows[0].at,1).status,'UNAVAILABLE');
assert.equal(forecastWindow(rows,'invalid',3).status,'UNAVAILABLE');
assert.equal(usesForecast('auto','2026-10-28T10:00:00Z',Date.parse('2026-10-28T10:30:00Z')),false);
assert.equal(usesForecast('auto','2026-10-28T11:00:00Z',Date.parse('2026-10-28T10:30:00Z')),true);
assert.equal(usesForecast('official',rows[0].at),false);
assert.equal(usesForecast('forecast',rows[0].at),true);
console.log('PASS 15 forecast-window checks: temporal evolution, boundaries, incomplete hours, auto mode');
